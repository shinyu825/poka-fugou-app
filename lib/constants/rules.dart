/// ルール画面の 1 節（見出し・箇条書き・表）
class RuleSection {
  final String title;
  final List<String> lines;

  /// 表（先頭の行が見出し。空なら表なし）
  final List<List<String>> table;

  /// 表の下の補足
  final String? note;

  const RuleSection({
    required this.title,
    this.lines = const [],
    this.table = const [],
    this.note,
  });
}

